-- 초기 스키마
-- PostgreSQL / H2(PostgreSQL 모드) 공용

CREATE TABLE subscriptions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name            VARCHAR(100)   NOT NULL,
    category                VARCHAR(30)    NOT NULL,
    fee                     NUMERIC(12, 2) NOT NULL,
    billing_cycle           VARCHAR(20)    NOT NULL,
    billing_day             INTEGER,
    start_date              DATE           NOT NULL,
    next_billing_date       DATE           NOT NULL,
    monthly_expense         NUMERIC(12, 2) NOT NULL,
    status                  VARCHAR(20)    NOT NULL,
    cancellation_scheduled_at DATE,
    remind_days_before      INTEGER        NOT NULL,
    owner_email             VARCHAR(255)   NOT NULL,
    memo                    VARCHAR(2000),
    created_at              TIMESTAMP      NOT NULL,
    updated_at              TIMESTAMP      NOT NULL
);

CREATE INDEX idx_subscriptions_owner_status ON subscriptions (owner_email, status);
CREATE INDEX idx_subscriptions_next_billing ON subscriptions (next_billing_date);

CREATE TABLE billing_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT         NOT NULL,
    billing_date    DATE           NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    memo            VARCHAR(255),
    created_at      TIMESTAMP      NOT NULL,
    updated_at      TIMESTAMP      NOT NULL,
    CONSTRAINT fk_billing_records_subscription
        FOREIGN KEY (subscription_id) REFERENCES subscriptions (id)
);

CREATE INDEX idx_billing_records_subscription ON billing_records (subscription_id, billing_date);

CREATE TABLE notification_histories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT       NOT NULL,
    type            VARCHAR(30)  NOT NULL,
    title           VARCHAR(255) NOT NULL,
    message         VARCHAR(1000),
    sent_at         TIMESTAMP    NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    CONSTRAINT fk_notification_histories_subscription
        FOREIGN KEY (subscription_id) REFERENCES subscriptions (id)
);

CREATE INDEX idx_notification_histories_subscription ON notification_histories (subscription_id, sent_at);
