-- 공유 구독 멤버와 월별 정산 기록

CREATE TABLE subscription_shares (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT         NOT NULL,
    member_name     VARCHAR(50)    NOT NULL,
    share_amount    NUMERIC(12, 2) NOT NULL,
    created_at      TIMESTAMP      NOT NULL,
    updated_at      TIMESTAMP      NOT NULL,
    CONSTRAINT fk_subscription_shares_subscription
        FOREIGN KEY (subscription_id) REFERENCES subscriptions (id) ON DELETE CASCADE
);

CREATE INDEX idx_subscription_shares_subscription ON subscription_shares (subscription_id);
CREATE UNIQUE INDEX uk_subscription_shares_member ON subscription_shares (subscription_id, member_name);

CREATE TABLE settlement_records (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    share_id   BIGINT      NOT NULL,
    period     VARCHAR(7)  NOT NULL,
    settled    BOOLEAN     NOT NULL DEFAULT FALSE,
    settled_at DATE,
    created_at TIMESTAMP   NOT NULL,
    updated_at TIMESTAMP   NOT NULL,
    CONSTRAINT fk_settlement_records_share
        FOREIGN KEY (share_id) REFERENCES subscription_shares (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uk_settlement_records_share_period ON settlement_records (share_id, period);
