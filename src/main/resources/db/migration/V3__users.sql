-- Google 로그인 사용자와 동의 기록

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub           VARCHAR(255) NOT NULL,
    email                VARCHAR(255) NOT NULL,
    name                 VARCHAR(100),
    picture_url          VARCHAR(500),
    birth_year           INTEGER,
    occupation           VARCHAR(30),
    household_size       INTEGER,
    interests            VARCHAR(500),
    memberships          VARCHAR(1000),
    onboarding_completed BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMP    NOT NULL,
    updated_at           TIMESTAMP    NOT NULL
);

CREATE UNIQUE INDEX uk_users_google_sub ON users (google_sub);
CREATE UNIQUE INDEX uk_users_email ON users (email);

CREATE TABLE user_consents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL,
    consent_type VARCHAR(30) NOT NULL,
    version      VARCHAR(20) NOT NULL,
    agreed       BOOLEAN     NOT NULL,
    agreed_at    TIMESTAMP   NOT NULL,
    created_at   TIMESTAMP   NOT NULL,
    updated_at   TIMESTAMP   NOT NULL,
    CONSTRAINT fk_user_consents_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uk_user_consents_type_version ON user_consents (user_id, consent_type, version);
